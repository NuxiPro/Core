// packages/shared/types/task.ts
import type { ColumnId } from "../../config/index";
import type { PriorityLabel } from "./priority-level";

/**
 * Task information
 */
export type Task = {
  id: string;               // UUID V7 of the task, generated by the backend
  colId: ColumnId;          // Column id as a string
  title: string;
  description?: string;
  userId: string;           // Task owner
  priority?: PriorityLabel; // Task priority
  Isarchived?: boolean;     // Task archive status
  positionString: string;   // Task position (fractional indexing)
  dueDate?: string | null;  // Optional due date (ex: "2026-09-30")
  createdAt: string;        // Creation date set when the task is created
  updatedAt?: string;       // Optional modification date
};

/**
 * Dedicated view for archived tasks in the side panel (Sheet)
 */
export type ArchivedTask = {
  id: Task['id'];
  title: Task["title"];
  description?: Task["description"];
  userId: Task["userId"];
  archivedAt: string;      // Required: effective archival date
  createdAt: Task["createdAt"];
};


/** Lightweight summary for the initial list (id + title max 255 bytes) */
export type TaskSummary = Pick<
  Task,
  "id" | "title" | "colId" | "createdAt" | "positionString" | "priority" | "dueDate"
>;

// What the client sends for creation
export type CreateTaskInput = Pick<Task, "title" | "colId">;

// Drag & drop payload: column change
export type MoveTaskInput = Pick<Task, "id" | "colId">;
